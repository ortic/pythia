//! Structural table model and the ALTER-based diff between two tables.

use std::collections::BTreeMap;

use pythia_db::oracle::Connection;

use crate::Error;
use crate::script::{Phase, SyncStatement};

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct TableDef {
    pub name: String,
    pub columns: Vec<ColumnDef>,
    pub comment: Option<String>,
    pub constraints: Vec<ConstraintDef>,
    pub indexes: Vec<IndexDef>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnDef {
    pub name: String,
    /// Full type, e.g. `VARCHAR2(30 CHAR)`, `NUMBER(10,2)`, `DATE`.
    pub data_type: String,
    pub nullable: bool,
    pub default: Option<String>,
    pub comment: Option<String>,
    /// An identity column (12.1+), made as `generation.identity` says; it
    /// has no default of its own.
    pub identity: bool,
    /// How Oracle fills the column, beyond a default (#458, #459).
    pub generation: Generation,
}

/// What a column is beyond its type and default (#458, #459): read as a column
/// with a default, a virtual column was made one with its expression as
/// the default (ORA-00904), a DEFAULT ON NULL lost it, an invisible column
/// was left out, an identity ALWAYS made BY DEFAULT ON NULL.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Generation {
    /// A virtual column's expression: `GENERATED ALWAYS AS (…) VIRTUAL`.
    pub virtual_expr: Option<String>,
    /// INVISIBLE (12.1): `select *` leaves it out.
    pub invisible: bool,
    /// DEFAULT ON NULL (12.1): an explicit NULL takes the default too.
    pub on_null: bool,
    /// How an identity column is generated.
    pub identity: IdentityMode,
}

/// How an identity column takes values.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum IdentityMode {
    /// From its sequence, also for an explicit NULL.
    #[default]
    ByDefaultOnNull,
    /// From its sequence where no value is given.
    ByDefault,
    /// Only from its sequence: no value may be given.
    Always,
}

impl ColumnDef {
    /// `name type [invisible] [default [on null] …] [not null]`, as in
    /// `CREATE TABLE` and `ALTER TABLE … ADD`; a virtual column `name type
    /// generated always as (…) virtual`. INVISIBLE goes before DEFAULT and
    /// GENERATED, as Oracle reads it.
    fn definition(&self) -> String {
        let g = &self.generation;
        let invisible = if g.invisible { " invisible" } else { "" };
        let head = format!("{} {}{invisible}", ident(&self.name), self.data_type);
        let not_null = if self.nullable { "" } else { " not null" };
        if let Some(expr) = &g.virtual_expr {
            return format!("{head} generated always as ({expr}) virtual{not_null}");
        }
        if self.identity {
            let mode = match g.identity {
                IdentityMode::ByDefaultOnNull => "by default on null",
                IdentityMode::ByDefault => "by default",
                IdentityMode::Always => "always",
            };
            return format!("{head} generated {mode} as identity");
        }
        let default = self
            .default
            .as_ref()
            .map(|d| format!(" default {}{d}", if g.on_null { "on null " } else { "" }))
            .unwrap_or_default();
        format!("{head}{default}{not_null}")
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ConstraintKind {
    Primary,
    Unique,
    Foreign,
    Check,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConstraintDef {
    pub name: String,
    pub kind: ConstraintKind,
    pub columns: Vec<String>,
    /// Referenced table and columns for foreign keys.
    pub references: Option<(String, Vec<String>)>,
    pub on_delete: Option<String>,
    pub condition: Option<String>,
    /// Name was generated by Oracle (`SYS_C...`): match by definition.
    pub generated: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IndexDef {
    pub name: String,
    pub unique: bool,
    /// Column names or expressions, in index order (with `DESC` if needed).
    pub columns: Vec<String>,
    pub generated: bool,
    /// What it is beyond its columns (#467).
    pub kind: IndexKind,
}

/// What an index is beyond its columns (#467): a bitmap index was made a
/// B-tree, a reverse, compressed, invisible or local one a plain one, and
/// the differences weren't seen.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct IndexKind {
    pub bitmap: bool,
    /// `compress 1`, `reverse`, `invisible`, `local`, as CREATE INDEX
    /// writes them.
    pub attributes: Vec<String>,
}

impl ConstraintDef {
    /// Definition without the name, for matching generated constraints.
    fn signature(&self) -> String {
        format!(
            "{:?}|{}|{:?}|{:?}|{}",
            self.kind,
            self.columns.join(","),
            self.references,
            self.on_delete,
            self.condition
                .as_deref()
                .map(normalize_condition)
                .unwrap_or_default()
        )
    }

    fn same_definition(&self, other: &Self) -> bool {
        self.signature() == other.signature()
    }

    /// `[CONSTRAINT name] PRIMARY KEY (...)` etc.
    pub fn definition(&self) -> String {
        let name = if self.generated {
            String::new()
        } else {
            format!("constraint {} ", ident(&self.name))
        };
        let cols = self
            .columns
            .iter()
            .map(|c| ident(c))
            .collect::<Vec<_>>()
            .join(", ");
        match self.kind {
            ConstraintKind::Primary => format!("{name}primary key ({cols})"),
            ConstraintKind::Unique => format!("{name}unique ({cols})"),
            ConstraintKind::Check => format!(
                "{name}check ({})",
                self.condition.as_deref().unwrap_or("1 = 1")
            ),
            ConstraintKind::Foreign => {
                let (table, ref_cols) = self.references.clone().unwrap_or_default();
                let ref_cols = ref_cols
                    .iter()
                    .map(|c| ident(c))
                    .collect::<Vec<_>>()
                    .join(", ");
                let on_delete = match self.on_delete.as_deref() {
                    Some("CASCADE") => " on delete cascade",
                    Some("SET NULL") => " on delete set null",
                    _ => "",
                };
                format!(
                    "{name}foreign key ({cols}) references {} ({ref_cols}){on_delete}",
                    ident(&table)
                )
            }
        }
    }
}

fn normalize_condition(c: &str) -> String {
    c.split_whitespace().collect::<Vec<_>>().join(" ")
}

impl IndexDef {
    fn signature(&self) -> String {
        format!(
            "{}|{}|{}|{}",
            self.unique,
            self.kind.bitmap,
            self.kind.attributes.join(" "),
            self.columns.join(",")
        )
    }

    /// `create [unique|bitmap] index … on table (…) [attributes] [local]`.
    fn create(&self, name: &str, table: &str) -> String {
        let kind = if self.unique {
            "unique "
        } else if self.kind.bitmap {
            "bitmap "
        } else {
            ""
        };
        let mut sql = format!(
            "create {kind}index {name} on {table} ({})",
            self.columns.join(", ")
        );
        for attribute in self.kind.attributes.iter().filter(|a| *a != "local") {
            sql.push_str(&format!(" {attribute}"));
        }
        if self.kind.attributes.iter().any(|a| a == "local") {
            sql.push_str(" local");
        }
        sql
    }
}

impl TableDef {
    /// The table as `CREATE TABLE` leaves it: columns with the primary,
    /// unique and check constraints, without foreign keys, indexes and
    /// comments (those follow as separate statements).
    pub fn as_created(&self) -> TableDef {
        TableDef {
            name: self.name.clone(),
            columns: self
                .columns
                .iter()
                .map(|c| ColumnDef {
                    comment: None,
                    ..c.clone()
                })
                .collect(),
            comment: None,
            constraints: self
                .constraints
                .iter()
                .filter(|c| c.kind != ConstraintKind::Foreign)
                .cloned()
                .collect(),
            indexes: Vec::new(),
        }
    }
}

/// What a new table gets besides its structure.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CreateOptions {
    /// Empty: the owner's default tablespace.
    pub tablespace: String,
    pub temporary: Temporary,
    pub partitioning: Option<Partitioning>,
}

/// How a table is partitioned.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum PartitionMethod {
    #[default]
    Range,
    /// Range, with new partitions created by the database as rows arrive.
    Interval,
    List,
    Hash,
}

impl PartitionMethod {
    pub fn label(self) -> &'static str {
        match self {
            PartitionMethod::Range => "range",
            PartitionMethod::Interval => "interval",
            PartitionMethod::List => "list",
            PartitionMethod::Hash => "hash",
        }
    }
}

/// The partitioning of a table: method, key and partitions.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Partitioning {
    pub method: PartitionMethod,
    /// Key columns (dictionary names).
    pub columns: Vec<String>,
    /// An interval table's interval, e.g. `NUMTOYMINTERVAL(1, 'MONTH')`.
    pub interval: String,
    pub partitions: Vec<PartitionDef>,
    /// Hash partitions by number when none are named.
    pub hash_count: u32,
}

/// A partition: its name (empty: the database names it) and its bound as
/// written in SQL (`100`, `MAXVALUE`, `'A', 'B'`, `DEFAULT`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PartitionDef {
    pub name: String,
    pub bound: String,
    /// Empty: the table's.
    pub tablespace: String,
}

impl PartitionDef {
    /// `partition p1 values less than (100) tablespace ts`, as in
    /// `CREATE TABLE` and `ALTER TABLE … ADD`.
    pub fn definition(&self, method: PartitionMethod) -> String {
        let mut text = "partition".to_owned();
        if !self.name.trim().is_empty() {
            text.push(' ');
            text.push_str(&ident(self.name.trim()));
        }
        let bound = self.bound.trim();
        match method {
            PartitionMethod::Range | PartitionMethod::Interval => {
                text.push_str(&format!(" values less than ({bound})"));
            }
            PartitionMethod::List => text.push_str(&format!(" values ({bound})")),
            PartitionMethod::Hash => {}
        }
        if !self.tablespace.trim().is_empty() {
            text.push_str(&format!(" tablespace {}", ident(self.tablespace.trim())));
        }
        text
    }
}

impl Partitioning {
    /// `partition by range (…) (partition …, …)`
    pub fn clause(&self) -> String {
        let columns = self
            .columns
            .iter()
            .map(|c| ident(c))
            .collect::<Vec<_>>()
            .join(", ");
        let by = match self.method {
            PartitionMethod::Range | PartitionMethod::Interval => "range",
            PartitionMethod::List => "list",
            PartitionMethod::Hash => "hash",
        };
        let mut text = format!("partition by {by} ({columns})");
        if self.method == PartitionMethod::Interval {
            text.push_str(&format!(" interval ({})", self.interval.trim()));
        }
        if self.method == PartitionMethod::Hash && self.partitions.is_empty() {
            text.push_str(&format!(" partitions {}", self.hash_count.max(1)));
            return text;
        }
        let partitions: Vec<String> = self
            .partitions
            .iter()
            .map(|p| p.definition(self.method))
            .collect();
        text.push_str(&format!("\n(\n  {}\n)", partitions.join(",\n  ")));
        text
    }
}

/// A global temporary table and what a commit does to its rows.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum Temporary {
    #[default]
    No,
    DeleteRows,
    PreserveRows,
}

/// Statements creating `def`: `CREATE TABLE` with the columns and the
/// primary, unique and check constraints, then the foreign keys, indexes and
/// comments, as the diff against the table as created.
pub fn create(def: &TableDef, options: &CreateOptions) -> Vec<SyncStatement> {
    let created = def.as_created();
    let lines: Vec<String> = created
        .columns
        .iter()
        .map(ColumnDef::definition)
        .chain(created.constraints.iter().map(ConstraintDef::definition))
        .collect();
    let kind = match options.temporary {
        Temporary::No => "table",
        _ => "global temporary table",
    };
    let mut sql = format!(
        "create {kind} {} (\n  {}\n)",
        ident(&def.name),
        lines.join(",\n  ")
    );
    match options.temporary {
        Temporary::No if !options.tablespace.trim().is_empty() => {
            sql.push_str(&format!(
                "\ntablespace {}",
                ident(options.tablespace.trim())
            ));
        }
        Temporary::DeleteRows => sql.push_str("\non commit delete rows"),
        Temporary::PreserveRows => sql.push_str("\non commit preserve rows"),
        Temporary::No => {}
    }
    if let Some(partitioning) = &options.partitioning {
        sql.push('\n');
        sql.push_str(&partitioning.clause());
    }
    let mut statements = vec![SyncStatement::new(Phase::Tables, def.name.clone(), sql)];
    statements.extend(diff(def, &created, false).statements);
    statements
}

/// Quotes an identifier as `Dialect::quote_ident` does, a reserved word
/// too (#303): plain uppercase names are written in lowercase.
pub fn ident(name: &str) -> String {
    let quoted = pythia_db::Dialect::ORACLE.quote_ident(name);
    if quoted == name {
        name.to_lowercase()
    } else {
        quoted
    }
}

fn quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

/// Result of comparing two tables.
#[derive(Debug, Clone, Default)]
pub struct TableDiff {
    pub statements: Vec<SyncStatement>,
    /// Differences that don't need (or can't get) a statement, e.g. column order.
    pub notes: Vec<String>,
}

impl TableDiff {
    pub fn is_empty(&self) -> bool {
        self.statements.is_empty()
    }
}

/// Statements that turn `target` into `source`. `drops` enables dropping
/// columns that only exist in the target (destructive).
/// `alter table … modify (col visible|invisible)` as `col` is.
fn visibility(table: &str, col: &ColumnDef) -> String {
    let visible = if col.generation.invisible {
        "invisible"
    } else {
        "visible"
    };
    format!(
        "alter table {table} modify ({} {visible})",
        ident(&col.name)
    )
}

pub fn diff(source: &TableDef, target: &TableDef, drops: bool) -> TableDiff {
    let t = ident(&source.name);
    let mut out = TableDiff::default();
    let mut out_notes = Vec::new();
    let mut push = |phase, sql: String, warning: Option<String>, enabled: bool| {
        out.statements.push(SyncStatement {
            phase,
            sql,
            plsql: false,
            warning,
            enabled,
            object: source.name.clone(),
        });
    };

    // Columns.
    let target_cols: BTreeMap<&str, &ColumnDef> = target
        .columns
        .iter()
        .map(|c| (c.name.as_str(), c))
        .collect();
    let source_cols: BTreeMap<&str, &ColumnDef> = source
        .columns
        .iter()
        .map(|c| (c.name.as_str(), c))
        .collect();
    for col in &source.columns {
        match target_cols.get(col.name.as_str()) {
            None => {
                let warning =
                    (!col.nullable && col.default.is_none() && !col.identity).then(|| {
                        "fails if the table has rows: NOT NULL column without default".to_owned()
                    });
                push(
                    Phase::Tables,
                    format!("alter table {t} add ({})", col.definition()),
                    warning,
                    true,
                );
            }
            // A virtual column's expression isn't a default (ORA-54025).
            Some(old)
                if old.generation.virtual_expr.is_some()
                    || col.generation.virtual_expr.is_some() =>
            {
                if norm_default(&old.generation.virtual_expr)
                    != norm_default(&col.generation.virtual_expr)
                    || old.data_type != col.data_type
                {
                    out_notes.push(format!(
                        "virtual column {} differs (not synchronized)",
                        col.name
                    ));
                }
                if old.generation.invisible != col.generation.invisible {
                    push(Phase::Tables, visibility(&t, col), None, true);
                }
                if old.comment != col.comment {
                    let comment = col.comment.as_deref().unwrap_or("");
                    push(
                        Phase::Comments,
                        format!(
                            "comment on column {t}.{} is {}",
                            ident(&col.name),
                            quote(comment)
                        ),
                        None,
                        true,
                    );
                }
            }
            Some(old) if old.identity || col.identity => {
                // An existing column can't become an identity column; the
                // identity's sequence stands in for a default.
                if old.identity != col.identity
                    || old.data_type != col.data_type
                    || old.generation.identity != col.generation.identity
                {
                    out_notes.push(format!(
                        "identity column {} differs (not synchronized)",
                        col.name
                    ));
                }
                if old.generation.invisible != col.generation.invisible {
                    push(Phase::Tables, visibility(&t, col), None, true);
                }
                if old.comment != col.comment {
                    let comment = col.comment.as_deref().unwrap_or("");
                    push(
                        Phase::Comments,
                        format!(
                            "comment on column {t}.{} is {}",
                            ident(&col.name),
                            quote(comment)
                        ),
                        None,
                        true,
                    );
                }
            }
            Some(old) => {
                let name = ident(&col.name);
                if old.data_type != col.data_type {
                    let warning = narrowing(&old.data_type, &col.data_type).then(|| {
                        format!(
                            "narrows {} from {} to {}: may fail or lose data",
                            col.name, old.data_type, col.data_type
                        )
                    });
                    push(
                        Phase::Tables,
                        format!("alter table {t} modify ({name} {})", col.data_type),
                        warning,
                        true,
                    );
                }
                // DEFAULT ON NULL is set with the default: a plain DEFAULT
                // turns it off.
                if norm_default(&old.default) != norm_default(&col.default)
                    || old.generation.on_null != col.generation.on_null
                {
                    let value = col.default.clone().unwrap_or_else(|| "null".into());
                    let on_null = if col.generation.on_null && col.default.is_some() {
                        "on null "
                    } else {
                        ""
                    };
                    push(
                        Phase::Tables,
                        format!("alter table {t} modify ({name} default {on_null}{value})"),
                        None,
                        true,
                    );
                }
                if old.generation.invisible != col.generation.invisible {
                    push(Phase::Tables, visibility(&t, col), None, true);
                }
                if old.nullable != col.nullable {
                    let (sql, warning) = if col.nullable {
                        (format!("alter table {t} modify ({name} null)"), None)
                    } else {
                        (
                            format!("alter table {t} modify ({name} not null)"),
                            Some(format!("fails if {} contains NULLs", col.name)),
                        )
                    };
                    push(Phase::Tables, sql, warning, true);
                }
                if old.comment != col.comment {
                    let comment = col.comment.as_deref().unwrap_or("");
                    push(
                        Phase::Comments,
                        format!("comment on column {t}.{name} is {}", quote(comment)),
                        None,
                        true,
                    );
                }
            }
        }
    }
    for col in &target.columns {
        if !source_cols.contains_key(col.name.as_str()) {
            push(
                Phase::Tables,
                format!("alter table {t} drop column {}", ident(&col.name)),
                Some(format!("drops column {} and its data", col.name)),
                drops,
            );
        }
    }
    let order = |cols: &[ColumnDef]| -> Vec<String> {
        cols.iter()
            .filter(|c| {
                source_cols.contains_key(c.name.as_str())
                    && target_cols.contains_key(c.name.as_str())
            })
            .map(|c| c.name.clone())
            .collect()
    };
    out.notes.extend(out_notes);
    if order(&source.columns) != order(&target.columns) {
        out.notes
            .push("column order differs (not synchronized)".into());
    }
    for col in source
        .columns
        .iter()
        .filter(|c| c.comment.is_some() && !target_cols.contains_key(c.name.as_str()))
    {
        let comment = col.comment.as_deref().unwrap_or("");
        out.statements.push(SyncStatement {
            phase: Phase::Comments,
            sql: format!(
                "comment on column {t}.{} is {}",
                ident(&col.name),
                quote(comment)
            ),
            plsql: false,
            warning: None,
            enabled: true,
            object: source.name.clone(),
        });
    }

    // Table comment.
    if source.comment != target.comment {
        out.statements.push(SyncStatement {
            phase: Phase::Comments,
            sql: format!(
                "comment on table {t} is {}",
                quote(source.comment.as_deref().unwrap_or(""))
            ),
            plsql: false,
            warning: None,
            enabled: true,
            object: source.name.clone(),
        });
    }

    // Constraints: match user-named ones by name, generated ones by definition.
    let find = |list: &[ConstraintDef], c: &ConstraintDef| -> Option<ConstraintDef> {
        if c.generated {
            list.iter().find(|o| o.same_definition(c)).cloned()
        } else {
            list.iter()
                .find(|o| o.name == c.name && !o.generated)
                .cloned()
        }
    };
    let drop_constraint = |c: &ConstraintDef, out: &mut TableDiff| {
        let phase = if c.kind == ConstraintKind::Foreign {
            Phase::DropForeignKeys
        } else {
            Phase::DropConstraints
        };
        out.statements.push(SyncStatement {
            phase,
            sql: format!("alter table {t} drop constraint {}", ident(&c.name)),
            plsql: false,
            warning: None,
            enabled: true,
            object: source.name.clone(),
        });
    };
    for c in &target.constraints {
        match find(&source.constraints, c) {
            None => drop_constraint(c, &mut out),
            Some(s) if !s.same_definition(c) => drop_constraint(c, &mut out),
            Some(_) => {}
        }
    }
    for c in &source.constraints {
        let missing = match find(&target.constraints, c) {
            None => true,
            Some(o) => !o.same_definition(c),
        };
        if missing {
            let phase = if c.kind == ConstraintKind::Foreign {
                Phase::ForeignKeys
            } else {
                Phase::Constraints
            };
            out.statements.push(SyncStatement {
                phase,
                sql: format!("alter table {t} add {}", c.definition()),
                plsql: false,
                warning: None,
                enabled: true,
                object: source.name.clone(),
            });
        }
    }

    // Indexes (constraint-backing indexes are excluded by the loader).
    let find_index = |list: &[IndexDef], i: &IndexDef| -> Option<IndexDef> {
        if i.generated {
            list.iter()
                .find(|o| o.signature() == i.signature())
                .cloned()
        } else {
            list.iter().find(|o| o.name == i.name).cloned()
        }
    };
    for i in &target.indexes {
        let keep = find_index(&source.indexes, i).is_some_and(|s| s.signature() == i.signature());
        if !keep {
            out.statements.push(SyncStatement {
                phase: Phase::DropIndexes,
                sql: format!("drop index {}", ident(&i.name)),
                plsql: false,
                warning: None,
                enabled: true,
                object: source.name.clone(),
            });
        }
    }
    for i in &source.indexes {
        let present =
            find_index(&target.indexes, i).is_some_and(|o| o.signature() == i.signature());
        if !present {
            let name = if i.generated {
                format!("{}_ix", source.name.to_lowercase())
            } else {
                ident(&i.name)
            };
            out.statements.push(SyncStatement {
                phase: Phase::Indexes,
                sql: i.create(&name, &t),
                plsql: false,
                warning: None,
                enabled: true,
                object: source.name.clone(),
            });
        }
    }
    out
}

fn norm_default(d: &Option<String>) -> Option<String> {
    d.as_ref()
        .map(|d| d.trim().to_owned())
        .filter(|d| !d.is_empty() && !d.eq_ignore_ascii_case("null"))
}

/// True if changing `from` to `to` can lose data (shorter strings, fewer digits).
pub fn narrowing(from: &str, to: &str) -> bool {
    let (base_from, args_from) = split_type(from);
    let (base_to, args_to) = split_type(to);
    if base_from != base_to {
        // Type family change: always risky.
        return true;
    }
    match (args_from.first(), args_to.first()) {
        (Some(a), Some(b)) if a > b => true,
        (None, Some(_)) => true,
        _ => matches!((args_from.get(1), args_to.get(1)), (Some(a), Some(b)) if a > b),
    }
}

fn split_type(t: &str) -> (String, Vec<u64>) {
    let t = t.to_ascii_uppercase();
    match t.split_once('(') {
        Some((base, rest)) => {
            let args = rest
                .trim_end_matches(')')
                .split(',')
                .filter_map(|a| a.split_whitespace().next().and_then(|n| n.parse().ok()))
                .collect();
            (base.trim().to_owned(), args)
        }
        None => (t.trim().to_owned(), Vec::new()),
    }
}

/// Loads the structure of all tables of `owner` (optionally a single table).
pub fn load(
    conn: &Connection,
    owner: &str,
    only: Option<&str>,
) -> Result<BTreeMap<String, TableDef>, Error> {
    let name = only.unwrap_or("%");
    let mut tables: BTreeMap<String, TableDef> = BTreeMap::new();
    for row in conn.query(
        "select t.table_name, c.comments from all_tables t \
           left join all_tab_comments c on c.owner = t.owner and c.table_name = t.table_name \
          where t.owner = :1 and t.table_name like :2 and t.nested = 'NO' and t.secondary = 'N' \
            and t.table_name not like 'BIN$%' and nvl(t.iot_type, '-') <> 'IOT_OVERFLOW' \
            and not exists (select 1 from all_mviews m where m.owner = t.owner and m.mview_name = t.table_name)",
        &[&owner, &name],
    )? {
        let (table, comment): (String, Option<String>) = row?.get_as()?;
        tables.insert(table.clone(), TableDef { name: table, comment, ..TableDef::default() });
    }

    // Identity columns, invisible ones and DEFAULT ON NULL came with 12.1.
    let twelve = pythia_db::compat::at_least(conn, 12, 1)?;
    let (identity, on_null, always) = if twelve {
        ("c.identity_column", "c.default_on_null", "")
    } else {
        ("'NO'", "'NO'", "null")
    };
    let always = if twelve {
        "(select i.generation_type from all_tab_identity_cols i where i.owner = c.owner \
           and i.table_name = c.table_name and i.column_name = c.column_name)"
            .to_owned()
    } else {
        always.to_owned()
    };
    for row in conn.query(
        &format!("select c.table_name, c.column_name, \
                case \
                  when c.data_type in ('NVARCHAR2', 'NCHAR') then \
                    c.data_type || '(' || c.char_length || ')' \
                  when c.data_type in ('VARCHAR2', 'CHAR') then \
                    c.data_type || '(' || decode(c.char_used, 'C', c.char_length || ' CHAR', c.data_length || ' BYTE') || ')' \
                  when c.data_type = 'RAW' then 'RAW(' || c.data_length || ')' \
                  when c.data_type = 'NUMBER' and c.data_precision is not null then \
                    'NUMBER(' || c.data_precision || nvl2(nullif(c.data_scale, 0), ',' || c.data_scale, '') || ')' \
                  when c.data_type = 'NUMBER' and c.data_scale = 0 then 'NUMBER(*,0)' \
                  when c.data_type = 'FLOAT' then 'FLOAT(' || c.data_precision || ')' \
                  else c.data_type end, \
                c.nullable, c.data_default, cc.comments, {identity}, c.virtual_column, \
                c.hidden_column, {on_null}, {always} \
           from all_tab_cols c \
           left join all_col_comments cc \
             on cc.owner = c.owner and cc.table_name = c.table_name and cc.column_name = c.column_name \
          where c.owner = :1 and c.table_name like :2 and c.user_generated = 'YES' \
          order by c.table_name, c.column_id nulls last, c.internal_column_id"),
        &[&owner, &name],
    )? {
        let row = row?;
        #[allow(clippy::type_complexity)]
        let (table, column, data_type, nullable, default, comment, identity): (
            String,
            String,
            String,
            String,
            Option<String>,
            Option<String>,
            String,
        ) = row.get_as()?;
        let virtual_column = row.get::<_, Option<String>>(7)?.as_deref() == Some("YES");
        let hidden = row.get::<_, Option<String>>(8)?.as_deref() == Some("YES");
        let on_null = row.get::<_, Option<String>>(9)?.as_deref() == Some("YES");
        let always = row.get::<_, Option<String>>(10)?;
        let identity = identity == "YES";
        let default = default.map(|d| d.trim().to_owned()).filter(|d| !d.is_empty());
        if let Some(t) = tables.get_mut(&table) {
            t.columns.push(ColumnDef {
                name: column,
                data_type,
                nullable: nullable == "Y",
                // An identity's default is its sequence's NEXTVAL, a virtual
                // column's its expression.
                default: default.clone().filter(|_| !identity && !virtual_column),
                comment,
                identity,
                generation: Generation {
                    virtual_expr: default.filter(|_| virtual_column),
                    invisible: hidden,
                    on_null: on_null && !identity,
                    identity: match (always.as_deref(), on_null) {
                        (Some("ALWAYS"), _) => IdentityMode::Always,
                        (_, true) => IdentityMode::ByDefaultOnNull,
                        _ => IdentityMode::ByDefault,
                    },
                },
            });
        }
    }

    let mut backing_indexes: Vec<(String, String)> = Vec::new();
    // Before 12.1 the condition is only the LONG SEARCH_CONDITION.
    let condition = if pythia_db::compat::at_least(conn, 12, 1)? {
        "k.search_condition_vc"
    } else {
        "k.search_condition"
    };
    for row in conn.query(
        &format!("select k.table_name, k.constraint_name, k.constraint_type, k.generated, \
                (select listagg(c.column_name, ',') within group (order by c.position) \
                   from all_cons_columns c where c.owner = k.owner and c.constraint_name = k.constraint_name), \
                r.table_name, \
                (select listagg(c.column_name, ',') within group (order by c.position) \
                   from all_cons_columns c where c.owner = r.owner and c.constraint_name = r.constraint_name), \
                k.delete_rule, {condition}, k.index_name \
           from all_constraints k \
           left join all_constraints r on r.owner = k.r_owner and r.constraint_name = k.r_constraint_name \
          where k.owner = :1 and k.table_name like :2 and k.constraint_type in ('P', 'U', 'R', 'C') \
            and k.table_name not like 'BIN$%' \
          order by k.table_name, k.constraint_name"),
        &[&owner, &name],
    )? {
        #[allow(clippy::type_complexity)]
        let (table, cname, ctype, generated, cols, ref_table, ref_cols, delete_rule, condition, index): (
            String,
            String,
            String,
            String,
            Option<String>,
            Option<String>,
            Option<String>,
            Option<String>,
            Option<String>,
            Option<String>,
        ) = row?.get_as()?;
        let kind = match ctype.as_str() {
            "P" => ConstraintKind::Primary,
            "U" => ConstraintKind::Unique,
            "R" => ConstraintKind::Foreign,
            _ => ConstraintKind::Check,
        };
        // NOT NULL checks are represented by `nullable`.
        if kind == ConstraintKind::Check
            && condition.as_deref().is_some_and(is_not_null_check)
        {
            continue;
        }
        if let Some(index) = index {
            backing_indexes.push((table.clone(), index));
        }
        let split = |s: Option<String>| s.map(|s| s.split(',').map(str::to_owned).collect()).unwrap_or_default();
        if let Some(t) = tables.get_mut(&table) {
            t.constraints.push(ConstraintDef {
                name: cname,
                kind,
                columns: split(cols),
                references: ref_table.map(|rt| (rt, split(ref_cols))),
                on_delete: delete_rule.filter(|d| d != "NO ACTION"),
                condition,
                generated: generated == "GENERATED NAME",
            });
        }
    }

    // A function-based or descending index's expressions are LONGs, read
    // on their own (#467).
    let mut expressions: BTreeMap<(String, u32), String> = BTreeMap::new();
    for row in conn.query(
        "select e.index_name, e.column_position, e.column_expression from all_ind_expressions e \
          where e.index_owner = :1 and e.table_name like :2",
        &[&owner, &name],
    )? {
        let (index, position, expression): (String, u32, Option<String>) = row?.get_as()?;
        expressions.insert(
            (index, position),
            expression.unwrap_or_default().trim().to_owned(),
        );
    }
    // Domain indexes, and globally partitioned ones, whose partitions the
    // model has no place for, aren't compared.
    let mut current: Option<(String, IndexDef)> = None;
    let mut found: Vec<(String, IndexDef)> = Vec::new();
    for row in conn.query(
        "select i.table_name, i.index_name, i.uniqueness, i.generated, i.index_type, \
                i.compression, i.prefix_length, i.visibility, \
                (select p.locality from all_part_indexes p \
                  where p.owner = i.owner and p.index_name = i.index_name), \
                c.column_position, c.column_name, c.descend \
           from all_indexes i \
           join all_ind_columns c on c.index_owner = i.owner and c.index_name = i.index_name \
          where i.table_owner = :1 and i.table_name like :2 \
            and i.index_type in ('NORMAL', 'NORMAL/REV', 'BITMAP', 'FUNCTION-BASED NORMAL', \
                                 'FUNCTION-BASED NORMAL/REV', 'FUNCTION-BASED BITMAP') \
            and i.table_name not like 'BIN$%' \
          order by i.table_name, i.index_name, c.column_position",
        &[&owner, &name],
    )? {
        let row = row?;
        #[allow(clippy::type_complexity)]
        let (table, index, uniqueness, generated, index_type, compression, prefix, visibility): (
            String,
            String,
            String,
            String,
            String,
            Option<String>,
            Option<u32>,
            Option<String>,
        ) = row.get_as()?;
        let locality: Option<String> = row.get(8)?;
        let position: u32 = row.get(9)?;
        let column: String = row.get(10)?;
        let descend: String = row.get(11)?;
        if backing_indexes
            .iter()
            .any(|(t, i)| *t == table && *i == index)
            || locality.as_deref() == Some("GLOBAL")
        {
            continue;
        }
        let expression = match expressions.get(&(index.clone(), position)) {
            Some(e) => e.clone(),
            None => format!("\"{column}\""),
        };
        let expression = if descend == "DESC" {
            format!("{expression} desc")
        } else {
            expression
        };
        if current
            .as_ref()
            .is_none_or(|(t, i)| *t != table || i.name != index)
        {
            found.extend(current.take());
            let mut attributes = Vec::new();
            match compression.as_deref() {
                Some("ENABLED") => attributes.push(match prefix {
                    Some(n) => format!("compress {n}"),
                    None => "compress".to_owned(),
                }),
                Some(advanced @ ("ADVANCED LOW" | "ADVANCED HIGH")) => {
                    attributes.push(format!("compress {}", advanced.to_lowercase()));
                }
                _ => {}
            }
            if index_type.ends_with("/REV") {
                attributes.push("reverse".to_owned());
            }
            if visibility.as_deref() == Some("INVISIBLE") {
                attributes.push("invisible".to_owned());
            }
            if locality.as_deref() == Some("LOCAL") {
                attributes.push("local".to_owned());
            }
            current = Some((
                table.clone(),
                IndexDef {
                    name: index,
                    unique: uniqueness == "UNIQUE",
                    columns: Vec::new(),
                    generated: generated == "Y",
                    kind: IndexKind {
                        bitmap: index_type.contains("BITMAP"),
                        attributes,
                    },
                },
            ));
        }
        if let Some((_, def)) = current.as_mut() {
            def.columns.push(expression);
        }
    }
    found.extend(current);
    for (table, index) in found {
        if let Some(t) = tables.get_mut(&table) {
            t.indexes.push(index);
        }
    }
    Ok(tables)
}

/// `"COL" IS NOT NULL` system constraints.
fn is_not_null_check(condition: &str) -> bool {
    let c = condition.trim();
    c.to_ascii_uppercase().ends_with(" IS NOT NULL")
        && !c.contains(" AND ")
        && !c.contains(" and ")
        && c.starts_with('"')
}

