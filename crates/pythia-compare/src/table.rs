    #[test]
    fn narrowing_detection() {
        assert!(narrowing("VARCHAR2(30 CHAR)", "VARCHAR2(10 CHAR)"));
        assert!(!narrowing("VARCHAR2(10 CHAR)", "VARCHAR2(30 CHAR)"));
        assert!(narrowing("NUMBER(10,2)", "NUMBER(10,0)"));
        assert!(narrowing("NUMBER", "NUMBER(5)"));
        assert!(narrowing("VARCHAR2(10 CHAR)", "NUMBER"));
        assert!(!narrowing("NUMBER(5)", "NUMBER(8)"));
    }

    #[test]
    fn creates_tables() {
        let mut def = base();
        def.columns[0].identity = true;
        def.columns[1].default = Some("'n/a'".into());
        def.columns[1].comment = Some("Full name".into());
        def.columns.push(col("DEPT_ID", "NUMBER(10)", true));
        def.comment = Some("Employees".into());
        def.constraints.push(ConstraintDef {
            name: "EMP_DEPT_FK".into(),
            kind: ConstraintKind::Foreign,
            columns: vec!["DEPT_ID".into()],
            references: Some(("DEPT".into(), vec!["ID".into()])),
            on_delete: Some("CASCADE".into()),
            condition: None,
            generated: false,
        });
        def.constraints.push(ConstraintDef {
            name: "SYS_C001".into(),
            kind: ConstraintKind::Check,
            columns: Vec::new(),
            references: None,
            on_delete: None,
            condition: Some("dept_id > 0".into()),
            generated: true,
        });
        def.indexes.push(IndexDef {
            name: "EMP_DEPT_IX".into(),
            unique: false,
            columns: vec!["DEPT_ID".into()],
            generated: false,
        });
        let statements = create(
            &def,
            &CreateOptions {
                tablespace: "USERS".into(),
                temporary: Temporary::No,
                partitioning: None,
            },
        );
        let sql: Vec<&str> = statements.iter().map(|s| s.sql.as_str()).collect();
        assert_eq!(
            sql,
            [
                "create table emp (\n  id NUMBER(10) generated by default on null as identity,\n  \
                 name VARCHAR2(30 CHAR) default 'n/a',\n  dept_id NUMBER(10),\n  \
                 constraint emp_pk primary key (id),\n  check (dept_id > 0)\n)\ntablespace users",
                "comment on column emp.name is 'Full name'",
                "comment on table emp is 'Employees'",
                "alter table emp add constraint emp_dept_fk foreign key (dept_id) references dept (id) on delete cascade",
                "create index emp_dept_ix on emp (DEPT_ID)",
            ]
        );
        let phases: Vec<Phase> = statements.iter().map(|s| s.phase).collect();
        assert_eq!(
            phases,
            [
                Phase::Tables,
                Phase::Comments,
                Phase::Comments,
                Phase::ForeignKeys,
                Phase::Indexes
            ]
        );

        let gtt = create(
            &base(),
            &CreateOptions {
                tablespace: "ignored".into(),
                temporary: Temporary::PreserveRows,
                partitioning: None,
            },
        );
        assert_eq!(
            gtt[0].sql,
            "create global temporary table emp (\n  id NUMBER(10) not null,\n  \
             name VARCHAR2(30 CHAR),\n  constraint emp_pk primary key (id)\n)\n\
             on commit preserve rows"
        );
    }

    #[test]
    fn partitioned_tables() {
        let part = |name: &str, bound: &str| PartitionDef {
            name: name.into(),
            bound: bound.into(),
            tablespace: String::new(),
        };
        let mut p = Partitioning {
            method: PartitionMethod::Range,
            columns: vec!["ID".into()],
            partitions: vec![part("P1", "100"), part("PMAX", "MAXVALUE")],
            ..Partitioning::default()
        };
        p.partitions[1].tablespace = "USERS".into();
        let options = CreateOptions {
            partitioning: Some(p.clone()),
            ..CreateOptions::default()
        };
        assert_eq!(
            create(&base(), &options)[0].sql,
            "create table emp (\n  id NUMBER(10) not null,\n  name VARCHAR2(30 CHAR),\n  \
             constraint emp_pk primary key (id)\n)\npartition by range (id)\n(\n  \
             partition p1 values less than (100),\n  \
             partition pmax values less than (MAXVALUE) tablespace users\n)"
        );
        p.method = PartitionMethod::Interval;
        p.interval = "1000".into();
        p.partitions.truncate(1);
        assert_eq!(
            p.clause(),
            "partition by range (id) interval (1000)\n(\n  partition p1 values less than (100)\n)"
        );
        p.method = PartitionMethod::List;
        p.columns = vec!["NAME".into()];
        p.partitions = vec![part("", "'A', 'B'"), part("P_OTHER", "DEFAULT")];
        assert_eq!(
            p.clause(),
            "partition by list (name)\n(\n  partition values ('A', 'B'),\n  \
             partition p_other values (DEFAULT)\n)"
        );
        p.method = PartitionMethod::Hash;
        p.partitions.clear();
        p.hash_count = 4;
        assert_eq!(p.clause(), "partition by hash (name) partitions 4");
    }

    #[test]
    fn identity_columns() {
        let mut source = base();
        source.columns.push(ColumnDef {
            identity: true,
            ..col("SEQ_NO", "NUMBER", false)
        });
        let d = diff(&source, &base(), false);
        assert_eq!(
            sqls(&d),
            ["alter table emp add (seq_no NUMBER generated by default on null as identity)"]
        );
        assert!(d.statements[0].warning.is_none(), "filled by the identity");
        // An existing column can't become one.
        let mut target = base();
        source = base();
        source.columns[0].identity = true;
        target.columns[0].comment = Some("old".into());
        let d = diff(&source, &target, false);
        assert_eq!(sqls(&d), ["comment on column emp.id is ''"]);
        assert_eq!(d.notes, ["identity column ID differs (not synchronized)"]);
    }

