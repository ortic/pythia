/// Case-insensitive keyword check.
pub fn is_keyword(word: &str) -> bool {
    contains(KEYWORDS, word)
}

/// Whether an identifier spelled `word` needs quotes on a database with
/// `syntax` (Oracle's list is the highlighter's, which errs on the side of
/// quoting; MySQL's has it too).
pub fn is_reserved(word: &str, syntax: crate::Syntax) -> bool {
    match syntax {
        crate::Syntax::Oracle => is_keyword(word),
        crate::Syntax::MySql => contains(MYSQL_RESERVED, word) || is_keyword(word),
        crate::Syntax::Postgres => contains(POSTGRES_RESERVED, word),
        crate::Syntax::TSql => contains(TSQL_RESERVED, word),
        crate::Syntax::Sqlite => contains(SQLITE_RESERVED, word),
    }
}

/// Case-insensitive lookup in a sorted, uppercase list.
fn contains(list: &[&str], word: &str) -> bool {
    // The longest word is 30 bytes; avoid allocating for longer words.
    if word.len() > 32 || !word.is_ascii() {
        return false;
    }
    let mut buf = [0u8; 32];
    let upper = &mut buf[..word.len()];
    upper.copy_from_slice(word.as_bytes());
    upper.make_ascii_uppercase();
    let upper = std::str::from_utf8(upper).expect("ascii");
    list.binary_search(&upper).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted() {
        for list in [
            KEYWORDS,
            MYSQL_RESERVED,
            POSTGRES_RESERVED,
            TSQL_RESERVED,
            SQLITE_RESERVED,
        ] {
            assert!(
                list.windows(2).all(|w| w[0] < w[1]),
                "lists must be sorted: {:?}",
                list.windows(2).find(|w| w[0] >= w[1])
            );
        }
        assert!(is_reserved("Rank", crate::Syntax::MySql));
        assert!(is_reserved("order", crate::Syntax::MySql));
        assert!(!is_reserved("status", crate::Syntax::MySql));
        assert!(is_reserved("order", crate::Syntax::Postgres));
        assert!(!is_reserved("public", crate::Syntax::Postgres));
        assert!(is_reserved("Public", crate::Syntax::TSql));
        assert!(!is_reserved("name", crate::Syntax::TSql));
        assert!(is_reserved("Order", crate::Syntax::Sqlite));
        assert!(!is_reserved("key", crate::Syntax::Sqlite));
    }

    #[test]
    fn lookup() {
        assert!(is_keyword("select"));
        assert!(is_keyword("Pls_Integer"));
        assert!(!is_keyword("employees"));
    }
}
