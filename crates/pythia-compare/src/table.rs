    fn col(name: &str, ty: &str, nullable: bool) -> ColumnDef {
        ColumnDef {
            name: name.into(),
            data_type: ty.into(),
            nullable,
            default: None,
            comment: None,
            identity: false,
            generation: Default::default(),
        }
    }

    fn pk(name: &str, cols: &[&str], generated: bool) -> ConstraintDef {
        ConstraintDef {
            name: name.into(),
            kind: ConstraintKind::Primary,
            columns: cols.iter().map(|c| c.to_string()).collect(),
            references: None,
            on_delete: None,
            condition: None,
            generated,
        }
    }

    fn base() -> TableDef {
        TableDef {
            name: "EMP".into(),
            columns: vec![
                col("ID", "NUMBER(10)", false),
                col("NAME", "VARCHAR2(30 CHAR)", true),
            ],
            comment: None,
            constraints: vec![pk("EMP_PK", &["ID"], false)],
            indexes: vec![],
        }
    }

    fn sqls(d: &TableDiff) -> Vec<String> {
        d.statements
            .iter()
            .map(|s| format!("{}{}", if s.enabled { "" } else { "-- " }, s.sql))
            .collect()
    }

